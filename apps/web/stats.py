"""Deterministic cycle statistics for the clinician report.

Never use an LLM to compute these values. Gemini may only narrate after
numbers are calculated here.
"""

from __future__ import annotations

import math
import statistics
from dataclasses import dataclass
from datetime import date
from typing import Sequence

from models import build_cycle_model, detect_period_starts


@dataclass(frozen=True)
class CycleStats:
    cycles_logged: int
    mean: float | None
    median: float | None
    mode: float | None
    range_span: float | None
    stdev: float | None
    lengths: tuple[int, ...]
    flags: tuple[str, ...]
    bar_counts: tuple[tuple[int, int], ...]  # (length, count) sorted


def _mode(values: Sequence[float]) -> float | None:
    if not values:
        return None
    try:
        return float(statistics.mode(values))
    except statistics.StatisticsError:
        counts: dict[float, int] = {}
        for value in values:
            counts[value] = counts.get(value, 0) + 1
        top = max(counts.values())
        return min(value for value, count in counts.items() if count == top)


def compute_cycle_stats(
    checkins: Sequence[dict],
    *,
    today: date | None = None,
) -> CycleStats:
    today = today or date.today()
    starts, _ = detect_period_starts(checkins)
    state = build_cycle_model(checkins, today=today, tracking_mode="period_date")
    lengths = list(state.valid_cycle_lengths)
    flags: list[str] = []
    if state.excluded_cycle_count:
        flags.append(
            f"{state.excluded_cycle_count} possible missed or invalid cycle "
            "length(s) excluded from fitting."
        )
    if lengths and (max(lengths) - min(lengths)) >= 7:
        flags.append("Cycle length range is 7 or more days.")
    if len(lengths) >= 4:
        outliers = sum(1 for length in lengths[-4:] if length < 21 or length > 35)
        if outliers >= 3:
            flags.append(
                "Three of the last four valid cycles were outside 21 to 35 days."
            )

    if not lengths:
        return CycleStats(
            cycles_logged=0,
            mean=None,
            median=None,
            mode=None,
            range_span=None,
            stdev=None,
            lengths=(),
            flags=tuple(flags),
            bar_counts=(),
        )

    values = [float(length) for length in lengths]
    mean = statistics.fmean(values)
    median = float(statistics.median(values))
    mode = _mode(values)
    range_span = max(values) - min(values)
    stdev = float(statistics.pstdev(values)) if len(values) > 1 else 0.0

    counts: dict[int, int] = {}
    for length in lengths:
        counts[length] = counts.get(length, 0) + 1
    bar_counts = tuple(sorted(counts.items()))

    return CycleStats(
        cycles_logged=len(lengths),
        mean=mean,
        median=median,
        mode=mode,
        range_span=range_span,
        stdev=stdev,
        lengths=tuple(lengths),
        flags=tuple(flags),
        bar_counts=bar_counts,
    )


def format_stat(value: float | None, *, digits: int = 1) -> str:
    if value is None:
        return "—"
    if math.isclose(value, round(value)):
        return str(int(round(value)))
    return f"{value:.{digits}f}"


def build_report_pdf_bytes(
    stats: CycleStats,
    *,
    title: str = "Cadence summary",
    synthetic: bool = False,
) -> bytes:
    """Visually styled PDF built without third-party deps."""
    def esc(text: str) -> str:
        bs = chr(92)
        return text.replace(bs, bs + bs).replace("(", bs + "(").replace(")", bs + ")")

    lines: list[tuple[str, str, int, tuple[float, float, float]]] = []
    lines.append(("F2", title, 22, (0.608, 0.106, 0.188)))
    lines.append(("F3", "Self-reported data", 11, (0.42, 0.36, 0.33)))
    lines.append(("F1", "", 10, (0.0, 0.0, 0.0)))
    lines.append(("F2", "Cycle summary", 14, (0.353, 0.059, 0.110)))
    rows = [
        ("Cycles logged", str(stats.cycles_logged)),
        ("Mean", format_stat(stats.mean)),
        ("Median", format_stat(stats.median)),
        ("Mode", format_stat(stats.mode)),
        ("Range", format_stat(stats.range_span)),
        ("Standard deviation", format_stat(stats.stdev)),
    ]
    for label, value in rows:
        lines.append(("F1", f"{label}: {value}", 12, (0.165, 0.102, 0.078)))
    if stats.flags:
        lines.append(("F2", "Flags", 12, (0.353, 0.059, 0.110)))
        for flag in stats.flags:
            lines.append(("F1", f"- {flag}", 11, (0.165, 0.102, 0.078)))
    else:
        lines.append(("F1", "Flags: none", 11, (0.165, 0.102, 0.078)))
    if stats.bar_counts:
        bars = ", ".join(f"{length}d x{count}" for length, count in stats.bar_counts)
        lines.append(("F2", "Length counts", 12, (0.353, 0.059, 0.110)))
        lines.append(("F1", bars, 11, (0.165, 0.102, 0.078)))
    lines.append(("F1", "", 10, (0.0, 0.0, 0.0)))
    lines.append(("F3", "Generated by Cadence", 9, (0.42, 0.36, 0.33)))

    content: list[str] = []
    content.append("q")
    content.append("0.788 0.635 0.294 RG 1.2 w 50 772 m 562 772 l S")
    content.append("Q")
    y = 750
    for font, text, size, color in lines:
        if text == "":
            y -= 8
            continue
        r, g, b = color
        safe = esc(text)
        content.append(
            "BT /" + font + " " + str(size) + " Tf " + f"{r:.3f} {g:.3f} {b:.3f}" + " rg 50 " + str(y) + " Td (" + safe + ") Tj ET"
        )
        y -= size + 6
    content.append("q 0.788 0.635 0.294 RG 0.8 w 50 " + str(y + 4) + " m 562 " + str(y + 4) + " l S Q")

    stream = chr(10).join(content).encode("latin-1", errors="replace")

    objects: list[bytes] = []
    objects.append(b"1 0 obj<< /Type /Catalog /Pages 2 0 R >>endobj" + b"\n")
    objects.append(b"2 0 obj<< /Type /Pages /Kids [3 0 R] /Count 1 >>endobj" + b"\n")
    objects.append(
        b"3 0 obj<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        + b"/Contents 4 0 R /Resources<< /Font<< /F1 5 0 R /F2 6 0 R /F3 7 0 R >> >> >>endobj"
        + b"\n"
    )
    objects.append(
        ("4 0 obj<< /Length " + str(len(stream)) + " >>stream" + chr(10)).encode("ascii")
        + stream
        + (chr(10) + "endstream" + chr(10) + "endobj" + chr(10)).encode("ascii")
    )
    objects.append(b"5 0 obj<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>endobj" + b"\n")
    objects.append(b"6 0 obj<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>endobj" + b"\n")
    objects.append(b"7 0 obj<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Oblique >>endobj" + b"\n")

    buffer = bytearray(b"%PDF-1.4" + b"\n")
    offsets = [0]
    for obj in objects:
        offsets.append(len(buffer))
        buffer.extend(obj)
    xref_pos = len(buffer)
    buffer.extend(("xref" + chr(10) + "0 " + str(len(offsets)) + chr(10)).encode("ascii"))
    buffer.extend(b"0000000000 65535 f " + b"\n")
    for offset in offsets[1:]:
        buffer.extend((str(offset).rjust(10, "0") + " 00000 n " + chr(10)).encode("ascii"))
    buffer.extend(
        ("trailer<< /Size " + str(len(offsets)) + " /Root 1 0 R >>" + chr(10) +
         "startxref" + chr(10) + str(xref_pos) + chr(10) + "%%EOF" + chr(10)).encode("ascii")
    )
    return bytes(buffer)
